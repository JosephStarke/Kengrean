// Collects every Korean string the app can speak, assigns each a voice, and writes:
//   audio/manifest.js        voice|text -> mp3 file, loaded by the app
//   tools/audio_jobs.json    work list for tools/gen_audio.py
// Usage: node tools/extract_tts.mjs [--prune]   (--prune deletes mp3s no longer used)
import { writeFileSync, readdirSync, unlinkSync, mkdirSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { resolve } from 'node:path';
import { loadContent, ROOT } from './load_content.mjs';

const { cast, units, packs } = loadContent();
const DEFAULT_VOICE = { id: 'ko-KR-SunHiNeural' };
const ALT_VOICE = { id: 'ko-KR-InJoonNeural' };
const HANGUL_ONLY = /^[가-힣\s]+$/;

// Must match KG.audio.voiceKey in js/audio.js.
const voiceKey = (v) => [v.id, v.pitch || '', v.rate || ''].join(',');
const jobs = new Map();

function add(text, voice = DEFAULT_VOICE) {
    if (!text || !/[가-힣A-Za-z]/.test(text) || !voice) return;
    const key = `${voiceKey(voice)}|${text}`;
    if (jobs.has(key)) return;
    const file = `audio/${createHash('sha1').update(key).digest('hex').slice(0, 12)}.mp3`;
    jobs.set(key, { file, text, voice: voice.id, pitch: voice.pitch || '+0Hz', rate: voice.rate || '+0%' });
}

// Practice sentences alternate between a female and a male voice for listening variety.
const alternate = (text) => (createHash('md5').update(text).digest()[0] % 2 ? ALT_VOICE : DEFAULT_VOICE);

function addWord(w) {
    add(w.ko);
    if (w.polite) add(w.polite);
}

// "It's a N." statements for the True/False picture game (must match KG.hangul.particles.copula).
function copula(noun) {
    const last = [...noun.replace(/[^가-힣]/g, '')].pop();
    return noun + (last && (last.charCodeAt(0) - 0xAC00) % 28 ? '이에요' : '예요');
}
const statement = (w) => w.pos === 'noun' && w.emoji && !w.ko.includes(' ') && add(`${copula(w.ko)}.`);

for (const unit of units) {
    (unit.vocab || []).forEach(addWord);
    (unit.vocab || []).forEach(statement);
    (unit.blocks || []).forEach((b) => add(b));
    for (const letter of unit.letters || []) {
        add(letter.say);
        if (HANGUL_ONLY.test(letter.name) && letter.name !== letter.say) add(letter.name);
    }
    for (const scene of unit.story?.scenes || []) {
        for (const line of scene.lines) add(line.ko, (cast[line.sp] || {}).voice ?? DEFAULT_VOICE);
        if (scene.check) {
            add(scene.check.q, cast.narrator.voice);
            scene.check.options.forEach((o) => add(o));
        }
    }
    for (const pattern of unit.patterns || []) pattern.examples.forEach((e) => add(e.ko, alternate(e.ko)));
    for (const sentence of unit.sentences || []) {
        add(sentence.ko, alternate(sentence.ko));
        if (sentence.blank) [sentence.blank, ...sentence.alts].forEach((t) => add(t));
    }
    // Sentence Builder tiles say themselves when placed (same split as Q.build in js/games.js).
    const sentences = [...(unit.sentences || []), ...(unit.patterns || []).flatMap((p) => p.examples)];
    for (const s of sentences) s.ko.split(' ').map((t) => t.replace(/[.,!?…]+$/, '')).forEach((t) => add(t));
}
// True/False answer buttons.
['맞아요', '아니에요'].forEach((t) => add(t));

for (const pack of packs) {
    pack.words.forEach(addWord);
    pack.words.forEach(statement);
}

const manifest = {};
for (const [key, job] of jobs) manifest[key] = job.file.slice('audio/'.length, -'.mp3'.length);
mkdirSync(resolve(ROOT, 'audio'), { recursive: true });
writeFileSync(resolve(ROOT, 'audio/manifest.js'),
    '// Generated by tools/extract_tts.mjs — do not edit.\nKG.setAudioManifest(' + JSON.stringify(manifest) + ');\n');
writeFileSync(resolve(ROOT, 'tools/audio_jobs.json'), JSON.stringify([...jobs.values()], null, 1));
console.log(`${jobs.size} audio clips in manifest`);

if (process.argv.includes('--prune')) {
    const used = new Set([...jobs.values()].map((j) => j.file.slice('audio/'.length)));
    let removed = 0;
    for (const name of readdirSync(resolve(ROOT, 'audio'))) {
        if (name.endsWith('.mp3') && !used.has(name)) {
            unlinkSync(resolve(ROOT, 'audio', name));
            removed++;
        }
    }
    console.log(`pruned ${removed} unused clip(s)`);
}
